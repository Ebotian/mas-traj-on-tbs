def pack_circles(n: int = 26) -> Iterable[Tuple[float, float, float]]:
    """Return a dense, valid packing, truncated to at most ``n`` circles."""
    if n <= 0:
        raise ValueError("n must be a positive integer.")

    count = min(n, len(_PACKING))
    margin = 1.0e-7
    return [(x, y, max(0.0, r - margin)) for x, y, r in _PACKING[:count]]
