VARIANTS = [
    ("exchange_opt", "exchange", None,
     "one_exchange run to a local optimum (== the frozen PC, as a check)"),
    ("greedy", "greedy", None,
     "classic greedy max-cut construction in a seeded random node order"),
    ("rand_part", "rand_part", None,
     "nx randomized_partitioning (i.i.d. p=1/2), no search -- the Delta floor"),
]
for k in K_VALUES:
    VARIANTS.append((f"exchange_k{k}", "exchange", k,
                     f"one_exchange truncated after {k} accepted improving swap(s)"))


def candidate_id(name):
    return f"l2_{name}"


def build_one(name, mode, max_swaps, description):
    source = TEMPLATE.format(mode=mode, max_swaps=max_swaps, description=description)
    meta = {
        "candidate_id": candidate_id(name),
        "schema": "a0.maxcut.candidate/v1",
        "kind": "ok",
        "role": "L2-decreasing-strength-positive-control",
        "version": "1.0.0",
        "purpose": description,
        "expected": {"status": "ok", "failure_kind": None},
    }
    return source.encode("utf-8"), (json.dumps(meta, sort_keys=True, indent=2) + "\n").encode("utf-8")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    base = REDESIGN / "candidates"
    written = []
    for name, mode, max_swaps, description in VARIANTS:
        d = base / name
        src, meta = build_one(name, mode, max_swaps, description)
        if args.check:
            if (d / "solution.py").read_bytes() != src or (d / "candidate.json").read_bytes() != meta:
                raise SystemExit(f"MISMATCH {d}")
        else:
            d.mkdir(parents=True, exist_ok=True)
            (d / "solution.py").write_bytes(src)
            (d / "candidate.json").write_bytes(meta)
        written.append({"name": name, "dir": str(d.relative_to(REDESIGN)),
                        "solution_sha256": hashlib.sha256(src).hexdigest(),
                        "mode": mode, "max_swaps": max_swaps})
        print(f"{'checked' if args.check else 'wrote'} {name:16s} mode={mode:9s} max_swaps={max_swaps}")
    if not args.check:
        (REDESIGN / "out" / "l2_candidates.json").write_text(
            json.dumps({"variants": written}, sort_keys=True, indent=2) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
