#!/usr/bin/env python3
"""L2 candidate: one_exchange run to a local optimum (== the frozen PC, as a check)

Auto-generated by redesign/gen/make_l2_candidates.py -- do not edit by hand.
Self-contained (§4): stdlib only, no network, no external files, no self-reported
score.  Starting partition b_i and the shuffle stream are the frozen ones, so the
only thing that varies across variants is the search strength.
"""

import argparse
import json
import random

MODE = 'exchange'
MAX_SWAPS = None

MASK64 = (1 << 64) - 1
BACKBONE = 0xA5A5A5A5A5A5A5A5


class Rng:
    """splitmix64, the frozen baseline stream (positive_control/baseline/solution.py)."""

    def __init__(self, seed):
        self.state = (int(seed) ^ 0x9E3779B97F4A7C15) & MASK64

    def next_u64(self):
        self.state = (self.state + 0x9E3779B97F4A7C15) & MASK64
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
        return z ^ (z >> 31)

    def bit(self):
        return self.next_u64() & 1


def baseline_assignment(n, seed):
    rng = Rng(int(seed) ^ BACKBONE)
    return [rng.bit() for _ in range(n)]


def load_graph(path):
    with open(path, "r", encoding="utf-8") as handle:
        document = json.load(handle)
    return document["graph_id"], int(document["n"]), [(int(u), int(v)) for u, v in document["edges"]]


def adjacent(n, edges):
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    return adj


def cut_size(edges, side):
    return sum(1 for u, v in edges if side[u] != side[v])


def one_exchange(n, edges, adj, assignment, seed, max_swaps):
    """Transliteration of the pinned NetworkX one_exchange, with an optional cap
    on the number of accepted improving swaps (`max_swaps=None` == the pin)."""
    side = list(assignment)
    current = cut_size(edges, side)
    accepted = 0
    while True:
        if max_swaps is not None and accepted >= max_swaps:
            break
        nodes = list(range(n))
        seed.shuffle(nodes)
        best_v, best_gain = None, 0
        for v in nodes:
            gain = 0
            sv = side[v]
            for u in adj[v]:
                gain += 1 if side[u] == sv else -1
            if best_v is None or gain > best_gain:
                best_v, best_gain = v, gain
        if best_gain <= 0:
            break
        side[best_v] ^= 1
        current += best_gain
        accepted += 1
    return side, current


def greedy_construction(n, edges, adj, seed):
    """Classic greedy: visit nodes in a seeded random order; each node joins the
    side that maximises its cut contribution to already-placed neighbours."""
    order = list(range(n))
    seed.shuffle(order)
    side = [-1] * n
    for v in order:
        n0 = n1 = 0
        for u in adj[v]:
            if side[u] == 0:
                n0 += 1
            elif side[u] == 1:
                n1 += 1
        side[v] = 0 if n0 <= n1 else 1
    return side


def randomized_partitioning(n, seed):
    """`nx.approximation.randomized_partitioning(G, seed, p=0.5)`: i.i.d. sides."""
    return [0 if seed.random() < 0.5 else 1 for _ in range(n)]


def run(graph_path, seed_int):
    graph_id, n, edges = load_graph(graph_path)
    adj = adjacent(n, edges)
    if MODE == "greedy":
        assignment = greedy_construction(n, edges, adj, random.Random(seed_int))
    elif MODE == "rand_part":
        assignment = randomized_partitioning(n, random.Random(seed_int))
    elif MODE == "exchange":
        assignment, _ = one_exchange(n, edges, adj, baseline_assignment(n, seed_int),
                                     random.Random(seed_int), MAX_SWAPS)
    else:
        raise SystemExit("unknown MODE")
    return graph_id, assignment


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--graph", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, required=True)
    args = ap.parse_args()
    graph_id, assignment = run(args.graph, args.seed)
    payload = {"schema": "a0.maxcut.partition/v1", "graph_id": graph_id,
                "assignment": [int(x) for x in assignment]}
    text = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True) + "\n"
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
